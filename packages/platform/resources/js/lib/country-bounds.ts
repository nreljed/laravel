export interface CountryBounds {
  bounds: [number, number, number, number];
  center: [number, number];
  minZoom: number;
  defaultZoom: number;
}

const ZOOM_LARGE = { minZoom: 3, defaultZoom: 4 };
const ZOOM_BIG = { minZoom: 4, defaultZoom: 5 };
const ZOOM_MEDIUM = { minZoom: 5, defaultZoom: 6 };
const ZOOM_SMALL = { minZoom: 6, defaultZoom: 7 };
const ZOOM_TINY = { minZoom: 7, defaultZoom: 8 };
const ZOOM_MICRO = { minZoom: 8, defaultZoom: 9 };

function c(
  swLat: number,
  swLng: number,
  neLat: number,
  neLng: number,
  zoom?: { minZoom: number; defaultZoom: number },
): CountryBounds {
  const z = zoom || ZOOM_SMALL;
  return {
    bounds: [swLat, swLng, neLat, neLng],
    center: [(swLat + neLat) / 2, (swLng + neLng) / 2],
    minZoom: z.minZoom,
    defaultZoom: z.defaultZoom,
  };
}

